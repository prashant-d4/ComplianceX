"""Pydantic models for Stage 3 cross-document audit verification and findings."""

from enum import Enum
from typing import List, Optional, Any, Dict
from pydantic import BaseModel, Field
from app.models.document import DocumentExtractionResult, SourceEvidence


class FindingReviewStatus(str, Enum):
    """Explicit review state of an audit finding."""
    NEEDS_MANUAL_REVIEW = "needs_manual_review"
    DISCREPANCY_FOUND = "discrepancy_found"
    NO_DISCREPANCY_DETECTED = "no_discrepancy_detected"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    RULE_VIOLATION = "rule_violation"


class FindingCategory(str, Enum):
    """Categorization of audit findings."""
    CROSS_DOCUMENT_MISMATCH = "cross_document_mismatch"
    EXPIRED_CERTIFICATE = "expired_certificate"
    MISSING_DOCUMENT = "missing_document"
    MISSING_VALUE = "missing_value"
    AMBIGUOUS_EXTRACTION = "ambiguous_extraction"
    RULE_VIOLATION = "rule_violation"


class FindingSeverity(str, Enum):
    """Deterministic severity classification based on regulatory impact."""
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class AuditEvidenceReference(BaseModel):
    """Source-linked evidence citation for either declared or extracted values."""
    source_file: str = Field(..., description="PDF filename or 'user_declaration'")
    document_category: str = Field(..., description="Document type or 'declared_form'")
    page_number: Optional[int] = Field(None, description="One-based page number (None for form declarations)")
    matched_text: str = Field(..., description="Verbatim source excerpt or form declaration label")
    bounding_box: Optional[List[float]] = Field(None, description="[x0, y0, x1, y1] in native PDF points")
    field_key: Optional[str] = Field(None, description="Identifier of the field associated with evidence")


class AuditFinding(BaseModel):
    """Detailed, traceable audit finding generated by deterministic rules."""
    finding_id: str = Field(..., description="Unique stable finding identifier within evaluation")
    rule_id: str = Field(..., description="Rule identifier (e.g. RULE-FACULTY-COUNT)")
    category: FindingCategory
    title: str
    description: str
    severity: FindingSeverity
    review_status: FindingReviewStatus
    declared_value: Optional[Any] = None
    source_value: Optional[Any] = None
    normalized_declared_value: Optional[Any] = None
    normalized_source_value: Optional[Any] = None
    unit: Optional[str] = None
    extraction_quality_score: Optional[float] = Field(
        None, description="Heuristic quality estimate [0.0, 1.0], or None if evidence missing"
    )
    review_required: bool = Field(False, description="True if manual evaluator intervention is required")
    source_evidence: List[AuditEvidenceReference] = Field(
        default_factory=list, description="Evidence references for both sides of the comparison"
    )
    explanation: str = Field(..., description="Plain-English explanation of the finding basis")
    evaluator_decision: Optional[str] = Field(
        None, description="Human reviewer decision: 'approved' | 'rejected' | 'escalated'"
    )
    evaluator_notes: Optional[str] = Field(None, description="Reviewer justification or audit note")
    decided_at: Optional[str] = Field(None, description="ISO timestamp of reviewer decision")
    original_review_status: Optional[FindingReviewStatus] = Field(
        None, description="Original automated review status prior to human decision"
    )


class AuditSummary(BaseModel):
    """Aggregate statistics for an institutional evaluation."""
    total_rules_evaluated: int = 0
    matched_count: int = 0
    discrepancy_count: int = 0
    needs_manual_review_count: int = 0
    insufficient_evidence_count: int = 0
    rule_violation_count: int = 0
    decided_count: int = 0
    approved_count: int = 0
    rejected_count: int = 0
    escalated_count: int = 0


class DeclaredInstitutionData(BaseModel):
    """Institutional figures declared by the applicant in intake form."""
    institution_name: str
    application_id: str
    institution_type: Optional[str] = None
    location: Optional[str] = None
    academic_year: Optional[str] = None
    submission_date: Optional[str] = None
    faculty_count: Optional[int] = None
    student_count: Optional[int] = None
    land_area_acres: Optional[float] = None
    built_up_area_sq_m: Optional[float] = None
    fire_safety_cert_number: Optional[str] = None
    fire_safety_expiry_date: Optional[str] = None


class EvaluationAuditResponse(BaseModel):
    """Comprehensive evaluation audit response returned to the frontend."""
    evaluation_id: str
    evaluation_date: str
    institution_name: str
    application_id: str
    processing_status: str = "completed"  # "completed" | "partial" | "failed"
    is_partial: bool = False
    document_extractions: List[DocumentExtractionResult] = Field(default_factory=list)
    findings: List[AuditFinding] = Field(default_factory=list)
    summary: AuditSummary
    warnings: List[str] = Field(default_factory=list)
    processing_errors: List[str] = Field(default_factory=list)
    created_at: Optional[str] = None
    updated_at: Optional[str] = None


class AuditExtractedRequest(BaseModel):
    """Request model for evaluating already-extracted document data."""
    declared_data: DeclaredInstitutionData
    documents: List[DocumentExtractionResult]
    evaluation_date: Optional[str] = None


class ReviewDecisionRequest(BaseModel):
    """Request model for submitting an evaluator review decision."""
    decision: str = Field(..., description="'approved' | 'rejected' | 'escalated'")
    notes: Optional[str] = Field(None, description="Reviewer justification note")


class EvaluationHistoryItem(BaseModel):
    """Summary item for historical evaluations list."""
    evaluation_id: str
    institution_name: str
    application_id: str
    created_at: str
    evaluation_date: str
    processing_status: str
    total_findings: int
    discrepancy_count: int
    rule_violation_count: int
    matched_count: int
    needs_review_count: int
    decided_count: int
    approved_count: int
    rejected_count: int
    document_count: int

